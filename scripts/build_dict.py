def write_tsv(name, rows):
    path = ROOT / name
    seen = set()
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            key = (row[0], row[1])
            if key in seen:
                continue
            seen.add(key)
            f.write("\t".join(str(x) for x in row) + "\n")
    print(f"wrote {path} ({path.stat().st_size} bytes)")


